#!/usr/bin/env python3
"""Runs the official Go `// run` tests (top-level files of $GOROOT/test) through go2js.

Each program is compiled with go2js, run under Node, and its output compared
with the .out file Go ships (a program with no .out file must simply exit 0).

    GO2JS=bin/go2js python3 tests/goroot/corpus/run.py [-w results.md]

Prints the pass count and every failure with its reason; with -w also writes
a Markdown table (tests/goroot/corpus/RESULTS.md is that table).
"""
import concurrent.futures as cf, glob, os, subprocess, sys, tempfile

GO2JS = os.environ.get("GO2JS") or os.environ.get("G2J") or "bin/go2js"
ROOT = subprocess.check_output(["go", "env", "GOROOT"], text=True).strip()
VERSION = subprocess.check_output(["go", "env", "GOVERSION"], text=True).strip()
TESTS = ROOT + "/test"
WORK = tempfile.mkdtemp(prefix="go2js-corpus-")

CATEGORIES = [
    ("unsupported conversion", "unsafe / raw memory (Pointer, StringHeader, SliceHeader, uintptr tricks)"),
    ("unsafe", "unsafe / raw memory (Pointer, StringHeader, SliceHeader, uintptr tricks)"),
    ("finaliz", "garbage collector and finalizers (a JavaScript heap can't be observed)"),
    ("MemProfileRate", "garbage collector and finalizers (a JavaScript heap can't be observed)"),
    ("never collected", "garbage collector and finalizers (a JavaScript heap can't be observed)"),
    ("liveness", "stack liveness / stack objects (no Go stack)"),
    ("syscall", "package syscall (not available)"),
    ("MakeFunc", "reflect.MakeFunc (not available)"),
    ("listing stdlib", "linker tests (need the Go toolchain's objects)"),
    ("TIMEOUT", "too slow (64-bit integer arithmetic through BigInt)"),
]


def category(status, reason, name):
    if name.startswith("link"):
        return "linker tests (need the Go toolchain's objects)"
    for key, label in CATEGORIES:
        if key in reason or key == status:
            return label
    if name.startswith("stack"):
        return "stack liveness / stack objects (no Go stack)"
    return "a real gap in go2js"


def run_one(path):
    name = os.path.basename(path)[:-3]
    out_dir = f"{WORK}/{name}"
    os.makedirs(out_dir, exist_ok=True)
    expected = path[:-3] + ".out"
    try:
        c = subprocess.run([GO2JS, "-module", "commonjs", "-o", out_dir + "/o.js", path],
                           capture_output=True, text=True, timeout=120)
        if c.returncode:
            return name, "COMPILE", (c.stderr or c.stdout)[:200].strip().replace("\n", " ")
        r = subprocess.run(["node", out_dir + "/o.js"], capture_output=True, text=True, timeout=30)
        if r.returncode:
            return name, "EXIT%d" % r.returncode, r.stderr[-200:].strip().replace("\n", " ")
        if os.path.exists(expected) and r.stdout + r.stderr != open(expected).read():
            return name, "OUT", "output differs from the .out file"
        return name, "PASS", ""
    except subprocess.TimeoutExpired:
        return name, "TIMEOUT", ""


def is_run_test(path):
    head = open(path, errors="ignore").read(400).split("\n")[:3]
    return any(line.strip() == "// run" for line in head)


def main():
    files = [f for f in sorted(glob.glob(TESTS + "/*.go")) if is_run_test(f)]
    with cf.ThreadPoolExecutor(8) as pool:
        results = list(pool.map(run_one, files))
    passed = sum(1 for r in results if r[1] == "PASS")
    total = len(results)
    print(f"{total} files; {passed} pass ({100 * passed / total:.1f}%)")
    for name, status, reason in results:
        if status != "PASS":
            print(name, status, reason[:150])
    if "-w" in sys.argv:
        target = sys.argv[sys.argv.index("-w") + 1]
        with open(target, "w") as f:
            f.write(f"# Official Go `// run` tests\n\n")
            f.write(f"Go `{VERSION}`: **{passed} of {total} pass ({100 * passed / total:.1f}%)**. "
                    "Generated by `tests/goroot/corpus/run.py`; do not edit by hand.\n\n")
            f.write("| Test | Result | Why |\n|---|---|---|\n")
            for name, status, reason in results:
                why = "" if status == "PASS" else category(status, reason, name)
                f.write(f"| `{name}` | {'pass' if status == 'PASS' else 'FAIL'} | {why} |\n")
    sys.exit(0)


main()
